    </div>

    <!-- SECTION 2 -->
    <h3 class="section-heading"><span class="sec-num">2.</span> SOP লেখার মূল উদ্দেশ্য</h3>

    <ul class="visa-list">
        <li>✔ আপনি একজন genuine student তা প্রমাণ করা</li>
        <li>✔ কোর্সটি আপনার career এর সাথে সম্পর্কযুক্ত</li>
        <li>✔ দেশে ফিরে কী করবেন তা স্পষ্টভাবে বলা</li>
        <li>✔ আপনার academic এবং professional যোগ্যতা দেখানো</li>
    </ul>

    <!-- SECTION 3 -->
    <h3 class="section-heading"><span class="sec-num">3.</span> SOP স্ট্রাকচার কেমন হবে?</h3>

    <p>SOP সাধারণত ৫–৭টি প্যারাগ্রাফে সাজানো হয়:</p>

    <ul class="visa-list">
        <li>✔ Introduction — আপনি কে, উদ্দেশ্য কী</li>
        <li>✔ Academic background</li>
        <li>✔ Professional experience (থাকলে)</li>
        <li>✔ কেন এই কোর্স</li>
        <li>✔ কেন এই দেশ ও বিশ্ববিদ্যালয়</li>
        <li>✔ Future career plan</li>
        <li>✔ Return assurance</li>
    </ul>

    <!-- SECTION 4 -->
    <h3 class="section-heading"><span class="sec-num">4.</span> SOP লেখার সময় যেসব ভুল করা যাবে না</h3>

    <ul class="visa-list">
        <li>❌ Copy-paste SOP ব্যবহার</li>
        <li>❌ Over-exaggerated information</li>
        <li>❌ Career gap লুকানো</li>
        <li>❌ একেবারে generic SOP লেখা</li>
    </ul>

    <div class="info-box">
        SOP অবশ্যই 100% আপনার তথ্য অনুযায়ী customize হতে হবে।
    </div>

    <!-- SECTION 5 -->
    <h3 class="section-heading"><span class="sec-num">5.</span> University SOP vs Visa SOP</h3>

    <ul class="visa-list">
        <li>✔ University SOP — Academic focus</li>
        <li>✔ Visa SOP — Future goal + Return assurance বেশি গুরুত্ব পায়</li>
    </ul>

    <!-- SECTION 6 -->
    <h3 class="section-heading"><span class="sec-num">6.</span> SOP লেখার জন্য প্রয়োজনীয় তথ্য</h3>

    <ul class="visa-list">
        <li>✔ Academic background</li>
        <li>✔ IELTS / কাজের অভিজ্ঞতা</li>
        <li>✔ কেন কোর্সটি বেছে নিয়েছেন</li>
        <li>✔ Family ties + Future plan</li>
        <li>✔ Financial sponsor details</li>
    </ul>

