    </p>

    <ul class="visa-list">
        <li>✔ কেন বিদেশে পড়তে চান</li>
        <li>✔ কেন এই দেশ / বিশ্ববিদ্যালয়</li>
        <li>✔ আপনার academic background</li>
        <li>✔ ভবিষ্যৎ career plan</li>
        <li>✔ Return assurance (ভিসার জন্য গুরুত্বপূর্ণ)</li>
    </ul>

    <div class="highlight-box">
